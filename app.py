import streamlit as st
import sqlite3
import pandas as pd

# 1. Ticket fare functions

def child_fare(quantity):
    return quantity * 5

def adult_fare(quantity):
    return quantity * 15

def senior_fare(quantity):
    return quantity * 10


# 2. Create database and table

conn = sqlite3.connect("bookings.db")

conn.execute("""
CREATE TABLE IF NOT EXISTS bookings (
    id INTEGER PRIMARY KEY AUTOINCREMENT,
    customer_name TEXT,
    child_tickets INTEGER,
    adult_tickets INTEGER,
    senior_tickets INTEGER,
    total_fare REAL
)
""")

conn.commit()
conn.close()


# 3. Function to save bookings

def save_booking(name, child, adult, senior, total):

    conn = sqlite3.connect("bookings.db")

    conn.execute("""
    INSERT INTO bookings
    (customer_name, child_tickets, adult_tickets,
     senior_tickets, total_fare)
    VALUES (?, ?, ?, ?, ?)
    """, (name, child, adult, senior, total))

    conn.commit()
    conn.close()


# 4. Function to view bookings

def view_bookings():

    conn = sqlite3.connect("bookings.db")

    data = pd.read_sql_query(
        "SELECT * FROM bookings", conn
    )

    conn.close()

    return data


# 5. Streamlit user interface

st.title("Cinema Ticket Booking")

st.write("Child: £5 | Adult: £15 | Senior Citizen: £10")

name = st.text_input("Customer Name")

child = st.number_input(
    "Child Tickets", min_value=0, step=1
)

adult = st.number_input(
    "Adult Tickets", min_value=0, step=1
)

senior = st.number_input(
    "Senior Citizen Tickets", min_value=0, step=1
)

total = child_fare(child) + adult_fare(adult) + senior_fare(senior)

st.subheader(f"Total Fare: £{total:.2f}")


# 6. Book Tickets button

if st.button("Book Tickets"):

    if not name.strip():
        st.error("Please enter your name.")

    elif total == 0:
        st.error("Please select at least one ticket.")

    else:
        save_booking(name, child, adult, senior, total)
        st.success("Booking saved successfully!")


# 7. View Bookings button

if st.button("View Bookings"):

    st.subheader("Booking Records")

    st.dataframe(view_bookings())
